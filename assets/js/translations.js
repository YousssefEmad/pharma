window.t = function (key) {
  const lang = (window.StorageService && StorageService.getLang()) || localStorage.getItem('pharmalink_lang') || 'ar';
  const dict = PharmaI18n[lang] || PharmaI18n.ar;
  return dict[key] !== undefined ? dict[key] : (PharmaI18n.en[key] || key);
};

window.setLang = function (lang) {
  if (!PharmaI18n[lang]) return;
  if (window.StorageService) StorageService.setLang(lang);
  else localStorage.setItem('pharmalink_lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
};
